/** True the first time per tab session: the Contour draws itself once, not on every visit. */
export function drawOnce(): boolean {
  try {
    if (sessionStorage.getItem('keyra.drawn')) return false;
    sessionStorage.setItem('keyra.drawn', '1');
    return true;
  } catch {
    return false; // storage blocked: skip the flourish rather than replay it
  }
}
