export type Lang = 'ar' | 'en';
export type LangPref = Lang | 'auto';

const dicts: Record<Lang, Record<Key, string>> = { en, ar };
let current: Lang = 'en';

export const setLang = (l: Lang): void => {
  current = l;
};

export function detectLang(pref: LangPref, navLang: string): Lang {
  if (pref !== 'auto') return pref;
  return navLang.toLowerCase().startsWith('ar') ? 'ar' : 'en';
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[current][key];
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** "12 accounts" with the Arabic plural forms of DESIGN §5. */
export function accountCount(n: number): string {
  if (current === 'en') return n === 1 ? '1 account' : `${n} accounts`;
  if (n === 0) return 'لا حسابات';
  if (n === 1) return 'حساب واحد';
  if (n === 2) return 'حسابان';
  if (n <= 10) return `${n} حسابات`;
  return `${n} حساباً`;
}

/** m:ss for countdowns. */
export function clock(ms: number): string {
  const s = Math.max(0, Math.ceil(ms / 1000));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}
